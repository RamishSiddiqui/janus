#!/usr/bin/env python3
"""Generates the reference pages under docs/reference/ from the source code.

The reference is built from the code itself (doc comments, schema, settings,
routes) so it cannot drift: CI runs `gen_reference.py --check` and fails when
the committed pages differ from what the source produces.

Usage:
    python docs/tools/gen_reference.py           # rewrite the pages
    python docs/tools/gen_reference.py --check   # exit 1 if they are stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "src-tauri" / "src"
WEB = ROOT / "src"
OUT = ROOT / "docs" / "reference"

PROBLEMS: list[str] = []

GENERATED = "<!-- Generated by docs/tools/gen_reference.py. Do not edit by hand. -->\n\n"


def sp(paths):
    """Sorts paths the same way on every platform (Windows compares case-insensitively)."""
    return sorted(paths, key=lambda p: p.as_posix())


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n")


def rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def clean_doc(lines: list[str]) -> str:
    """Joins `///` lines into one paragraph block, keeping blank lines."""
    out = []
    for line in lines:
        text = line.strip()
        text = text[3:] if text.startswith("///") else text
        out.append(text[1:] if text.startswith(" ") else text)
    return "\n".join(out).strip()


def md_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def split_params(params: str) -> list[str]:
    """Splits a Rust parameter list at top-level commas."""
    parts, depth, cur = [], 0, ""
    for ch in params:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w.capitalize() for w in rest)


# ── commands ───────────────────────────────────────────────────────────────

CMD_RE = re.compile(
    r"((?:[ \t]*///[^\n]*\n)*)"  # doc comment
    r"(?:[ \t]*#\[[^\]\n]*\]\n)*?"  # other attributes
    r"[ \t]*#\[tauri::command\]\n"
    r"(?:[ \t]*#\[[^\]\n]*\]\n)*"
    r"[ \t]*pub(?:\(crate\))? +async +fn +(\w+)\s*"
    r"(?:<[^>]*>)?\s*\((.*?)\)\s*->\s*([^{]+?)\s*\{",
    re.S,
)
CMD_RE_SYNC = re.compile(
    r"((?:[ \t]*///[^\n]*\n)*)"
    r"(?:[ \t]*#\[[^\]\n]*\]\n)*?"
    r"[ \t]*#\[tauri::command\]\n"
    r"(?:[ \t]*#\[[^\]\n]*\]\n)*"
    r"[ \t]*pub(?:\(crate\))? +fn +(\w+)\s*"
    r"(?:<[^>]*>)?\s*\((.*?)\)\s*->\s*([^{]+?)\s*\{",
    re.S,
)
INJECTED = ("AppHandle", "State<", "Window", "WebviewWindow", "Channel")


def browser_commands() -> set[str]:
    """Command names the browser may call (listed in web/rpc_*.rs)."""
    names: set[str] = set()
    for f in (SRC / "web").glob("rpc_*.rs"):
        if f.name == "rpc_tables.rs":
            continue
        names.update(re.findall(r'^\s*"(\w+)"\s*=>', read(f), re.M))
    return names


def collect_commands():
    cmds = []
    for f in sp((SRC / "commands").rglob("*.rs")):
        text = read(f)
        for rx in (CMD_RE, CMD_RE_SYNC):
            for m in rx.finditer(text):
                doc, name, params, ret = m.groups()
                args = []
                for p in split_params(params):
                    if ":" not in p:
                        continue
                    pname, ptype = (s.strip() for s in p.split(":", 1))
                    if any(ptype.startswith(i) or i in ptype for i in INJECTED):
                        continue
                    args.append((camel(pname.lstrip("_")), re.sub(r"\s+", " ", ptype)))
                cmds.append(
                    {
                        "name": name,
                        "module": f.relative_to(SRC / "commands").with_suffix("").as_posix(),
                        "doc": clean_doc(doc.strip("\n").split("\n")) if doc.strip() else "",
                        "args": args,
                        "ret": re.sub(r"\s+", " ", ret.strip()),
                        "file": rel(f),
                    }
                )
    return cmds


def check_registration(cmds) -> None:
    """Every command must appear in both lib.rs lists (specta and the Tauri handler)."""
    text = read(SRC / "lib.rs")
    blocks = {}
    for label, marker in (("collect_commands", "collect_commands!["), ("generate_handler", "generate_handler![")):
        start = text.find(marker)
        if start < 0:
            PROBLEMS.append(f"lib.rs has no {marker} list")
            blocks[label] = set()
            continue
        end = text.find("]", start + len(marker))
        body = re.sub(r"//[^\n]*", "", text[start + len(marker):end])
        names = {part.strip().split("::")[-1] for part in body.split(",") if part.strip()}
        blocks[label] = names
    declared = {c["name"] for c in cmds} | {"get_app_info"}
    for label, names in blocks.items():
        for missing in sorted(declared - names):
            PROBLEMS.append(f"command `{missing}` is not registered in lib.rs {label}")
        for extra in sorted(names - declared):
            PROBLEMS.append(f"lib.rs {label} lists `{extra}`, which is not a command")


def gen_commands() -> str:
    cmds = collect_commands()
    browser = browser_commands()
    by_module: dict[str, list] = {}
    for c in cmds:
        by_module.setdefault(c["module"], []).append(c)

    out = [GENERATED, "# Command reference\n\n"]
    out.append(
        f"Every backend command the frontend can call: **{len(cmds)} commands** in "
        f"{len(by_module)} modules. The desktop app calls them through Tauri's `invoke()`; "
        "a browser calls the ones marked **Browser** through `POST /api/rpc/{command}` "
        "(see {doc}`/developer/browser-server`). Arguments are sent as a JSON object with "
        "camelCase keys. A failed command rejects with `{ error, message }`.\n\n"
    )
    out.append(
        f"Browser-callable: **{len([c for c in cmds if c['name'] in browser])}** of {len(cmds)}. "
        "The rest read or write files on the host machine, manage the host (voice model "
        "downloads, network settings, account switching), or are not needed in a browser yet.\n\n"
    )
    out.append("| Module | Commands |\n|---|---|\n")
    for mod, items in sorted(by_module.items()):
        out.append(f"| [{mod}](#{mod.replace('/', '').replace('_', '-').lower()}) | {len(items)} |\n")
    out.append("\n")
    for mod, items in sorted(by_module.items()):
        anchor = mod.replace("/", "").replace("_", "-").lower()
        out.append(f"({anchor})=\n## {mod}\n\n")
        out.append(f"Source: `{items[0]['file']}`\n\n")
        for c in items:
            tag = " — **Browser**" if c["name"] in browser else ""
            out.append(f"### `{c['name']}`{tag}\n\n")
            if c["doc"]:
                out.append(c["doc"] + "\n\n")
            else:
                out.append("_No description in the source yet._\n\n")
            if c["args"]:
                out.append("| Argument | Type |\n|---|---|\n")
                for a, t in c["args"]:
                    out.append(f"| `{a}` | `{md_cell(t)}` |\n")
                out.append("\n")
            else:
                out.append("No arguments.\n\n")
            out.append(f"Returns `{md_cell(c['ret'])}`\n\n")
    return "".join(out)


# ── events ─────────────────────────────────────────────────────────────────

EVENT_RE = re.compile(r'emit(?:_scoped)?\(\s*"([^"]+)"')


def gen_events() -> str:
    seen: dict[str, set[str]] = {}
    for f in SRC.rglob("*.rs"):
        for m in EVENT_RE.finditer(read(f)):
            seen.setdefault(m.group(1), set()).add(rel(f))
    listeners: dict[str, set[str]] = {}
    for f in list(WEB.rglob("*.ts")) + list(WEB.rglob("*.svelte")):
        for m in re.finditer(r"listen(?:<[^>]*>)?\(\s*['\"]([\w:-]+)['\"]", read(f)):
            listeners.setdefault(m.group(1), set()).add(rel(f))
    out = [GENERATED, "# Event reference\n\n"]
    out.append(
        "The backend pushes these events to the screen while work is in progress. "
        "On the desktop they arrive through Tauri's event system; in a browser the same "
        "names and payloads arrive over the `/api/events` Server-Sent Events stream. "
        "Each event is delivered only to the account it belongs to "
        "(see {doc}`/developer/events`).\n\n"
    )
    out.append("| Event | Emitted from | Listened to in |\n|---|---|---|\n")
    for name in sorted(seen):
        src = ", ".join(f"`{s}`" for s in sorted(seen[name]))
        lis = ", ".join(f"`{s}`" for s in sorted(listeners.get(name, []))) or "—"
        out.append(f"| `{name}` | {src} | {lis} |\n")
    out.append("\n")
    return "".join(out)


# ── database ───────────────────────────────────────────────────────────────

TABLE_RE = re.compile(r"DEFINE TABLE (?:IF NOT EXISTS |OVERWRITE )?(\w+)([^;]*);")
FIELD_RE = re.compile(
    r"DEFINE FIELD (?:IF NOT EXISTS |OVERWRITE )?([\w.*]+)\s+ON(?: TABLE)?\s+(\w+)\s+([^;]*);"
)
INDEX_RE = re.compile(r"DEFINE INDEX (?:IF NOT EXISTS |OVERWRITE )?(\w+)\s+ON(?: TABLE)?\s+(\w+)\s+([^;]*);")


def gen_database() -> str:
    text = read(SRC / "db" / "schema.rs")
    tables: dict[str, dict] = {}
    for m in TABLE_RE.finditer(text):
        tables.setdefault(m.group(1), {"opts": " ".join(m.group(2).split()), "fields": [], "indexes": []})
    for m in FIELD_RE.finditer(text):
        name, table, rest = m.group(1), m.group(2), " ".join(m.group(3).split())
        tables.setdefault(table, {"opts": "", "fields": [], "indexes": []})["fields"].append((name, rest))
    for m in INDEX_RE.finditer(text):
        name, table, rest = m.group(1), m.group(2), " ".join(m.group(3).split())
        tables.setdefault(table, {"opts": "", "fields": [], "indexes": []})["indexes"].append((name, rest))

    out = [GENERATED, "# Database reference\n\n"]
    out.append(
        f"Janus stores everything in an embedded SurrealDB database ({len(tables)} tables). "
        "The schema below is read from `src-tauri/src/db/schema.rs`. Tables marked with an "
        "`owner_id` field belong to an account (see {doc}`/developer/accounts`).\n\n"
    )
    out.append("| Table | Fields | Indexes |\n|---|---|---|\n")
    for t, d in sorted(tables.items()):
        out.append(f"| [{t}](#table-{t.replace('_', '-')}) | {len(d['fields'])} | {len(d['indexes'])} |\n")
    out.append("\n")
    for t, d in sorted(tables.items()):
        out.append(f"(table-{t.replace('_', '-')})=\n## `{t}`\n\n")
        if d["opts"]:
            out.append(f"Definition: `{md_cell(d['opts'])}`\n\n")
        if d["fields"]:
            out.append("| Field | Definition |\n|---|---|\n")
            for n, r in d["fields"]:
                out.append(f"| `{n}` | `{md_cell(r)}` |\n")
            out.append("\n")
        if d["indexes"]:
            out.append("| Index | Definition |\n|---|---|\n")
            for n, r in d["indexes"]:
                out.append(f"| `{n}` | `{md_cell(r)}` |\n")
            out.append("\n")
    mig = read(SRC / "db" / "migrations.rs")
    rows = re.findall(r"version:\s*(\d+),\s*description:\s*\"([^\"]+)\"", mig)
    out.append("## Migrations\n\n")
    out.append(
        "Changes that plain `DEFINE ... IF NOT EXISTS` cannot express run once, in order, "
        "and are recorded in the `_migrations` table.\n\n"
    )
    out.append("| Version | What it does |\n|---|---|\n")
    for v, d in rows:
        out.append(f"| {v} | {md_cell(d)} |\n")
    out.append("\n")
    return "".join(out)


# ── settings ───────────────────────────────────────────────────────────────


def gen_settings() -> str:
    text = read(WEB / "lib" / "stores" / "settings.ts")
    iface = re.search(r"export interface AppSettings \{(.*?)\n\}", text, re.S)
    defaults = re.search(r"const defaultSettings[^=]*=\s*\{(.*?)\n\};", text, re.S)
    default_map: dict[str, str] = {}
    if defaults:
        for m in re.finditer(r"^\s{2}(\w+):\s*(.+?),?\s*$", defaults.group(1), re.M):
            default_map[m.group(1)] = m.group(2)
    rows = []
    if iface:
        doc: list[str] = []
        in_doc = False
        for line in iface.group(1).split("\n"):
            s = line.strip()
            if s.startswith("/**"):
                in_doc = True
                doc = []
                s = s[3:].strip()
            if in_doc:
                body = s.rstrip("*/").strip() if s.endswith("*/") else s
                body = body.lstrip("*").strip()
                if body:
                    doc.append(body)
                if s.endswith("*/"):
                    in_doc = False
                continue
            m = re.match(r"(\w+)\??:\s*([^;]+);", s)
            if m:
                rows.append((m.group(1), m.group(2).strip(), " ".join(doc)))
                doc = []
    out = [GENERATED, "# Settings reference\n\n"]
    out.append(
        f"The {len(rows)} app settings, read from `src/lib/stores/settings.ts`. They are saved "
        "in the browser's local storage on whichever device you use (a desktop window and a "
        "phone each keep their own). Long default values (the prompts) are shown as `(text)`.\n\n"
    )
    out.append("| Setting | Type | Default | Meaning |\n|---|---|---|---|\n")
    for name, typ, doc in rows:
        d = default_map.get(name, "")
        if len(d) > 40 or "`" in d:
            d = "(text)"
        out.append(f"| `{name}` | `{md_cell(typ)}` | `{md_cell(d)}` | {md_cell(doc) or '—'} |\n")
    out.append("\n")
    return "".join(out)


# ── HTTP API ───────────────────────────────────────────────────────────────


def gen_http() -> str:
    out = [GENERATED, "# HTTP API reference\n\n"]
    out.append(
        "The browser server (`src-tauri/src/web/`) exposes these endpoints. All are under `/api`. "
        "`POST`/`DELETE` requests need the header `x-janus-request: 1` and a same-origin `Origin`. "
        "Sessions use an HttpOnly cookie. Errors are `{ \"error\": kind, \"message\": text }` with "
        "kinds `unauthorized` (401), `validation` (400), `not_found` (404), `forbidden` (403) and "
        "`internal` (500).\n\n"
    )
    out.append("| Method | Path | Handler | Summary |\n|---|---|---|---|\n")
    rows = []
    for f in sp((SRC / "web").glob("*.rs")):
        text = read(f)
        for m in re.finditer(r'\.route\(\s*"([^"]+)",\s*(?:axum::routing::)?(\w+)\(([\w:]+)\)', text):
            path, method, handler = m.groups()
            prefix = "/api/auth" if f.name == "auth_routes.rs" else "/api"
            rows.append((method.upper(), prefix + path, handler, f, text))
        for m in re.finditer(r'\.route\(\s*"([^"]+)",\s*\n\s*(?:axum::routing::)?(\w+)\(([\w:]+)\)', text):
            path, method, handler = m.groups()
            rows.append((method.upper(), "/api" + path, handler, f, text))
    seen = set()
    for method, path, handler, f, text in rows:
        key = (method, path)
        if key in seen:
            continue
        seen.add(key)
        fn = handler.split("::")[-1]
        doc = ""
        for candidate in (f, *sp((SRC / "web").glob("*.rs"))):
            t = read(candidate)
            m = re.search(r"((?:[ \t]*///[^\n]*\n)+)[ \t]*pub async fn " + re.escape(fn) + r"\b", t) or re.search(
                r"((?:[ \t]*///[^\n]*\n)+)[ \t]*async fn " + re.escape(fn) + r"\b", t
            )
            if m:
                doc = clean_doc(m.group(1).strip("\n").split("\n"))
                break
        out.append(f"| {method} | `{path}` | `{fn}` | {md_cell(doc) or '—'} |\n")
    out.append("\n")
    return "".join(out)


# ── source map ─────────────────────────────────────────────────────────────


def first_doc(text: str, marker: str) -> str:
    lines = []
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith(marker):
            lines.append(s[len(marker):].strip())
        elif lines or (s and not s.startswith("//")):
            if lines:
                break
            if s and not s.startswith("#!["):
                break
    return " ".join(lines).strip()


def first_ts_comment(text: str) -> str:
    m = re.match(r"\s*(?:<script[^>]*>\s*)?/\*\*?\s*(.*?)\*/", text, re.S)
    if m:
        body = " ".join(re.sub(r"^\s*\*\s?", "", l) for l in m.group(1).split("\n"))
        return " ".join(body.split())
    lines = []
    for line in text.split("\n"):
        s = line.strip()
        if s.startswith("//") and not set(s) <= {"/", "=", "-", " ", "*"}:
            lines.append(s.lstrip("/ ").strip())
        elif lines or (s and not s.startswith("//")):
            break
    return " ".join(lines).strip()


def gen_source_map() -> str:
    out = [GENERATED, "# Source map\n\n"]
    out.append(
        "Every source file with its own summary line, taken from the file's leading comment. "
        "Use it to find where something lives.\n\n"
    )
    out.append("## Backend (`src-tauri/src`)\n\n| File | Purpose |\n|---|---|\n")
    for f in sp(SRC.rglob("*.rs")):
        d = first_doc(read(f), "//!")
        out.append(f"| `{f.relative_to(ROOT.joinpath('src-tauri')).as_posix()}` | {md_cell(d) or '—'} |\n")
    out.append("\n## Backend tests (`src-tauri/tests`)\n\n| File | Purpose |\n|---|---|\n")
    for f in sp((ROOT / "src-tauri" / "tests").glob("*.rs")):
        d = first_doc(read(f), "//!")
        out.append(f"| `src-tauri/tests/{f.name}` | {md_cell(d) or '—'} |\n")
    for title, folder in (
        ("Frontend routes (`src/routes`)", "routes"),
        ("Frontend components (`src/lib/components`)", "lib/components"),
        ("Frontend stores (`src/lib/stores`)", "lib/stores"),
        ("Frontend services (`src/lib/services`)", "lib/services"),
        ("Frontend utilities (`src/lib/utils`)", "lib/utils"),
        ("Frontend data and types (`src/lib/data`, `src/lib/types`, `src/lib/constants`)", None),
    ):
        out.append(f"\n## {title}\n\n| File | Purpose |\n|---|---|\n")
        if folder:
            files = sp((WEB / folder).rglob("*"))
        else:
            files = sp([p for d in ("lib/data", "lib/types", "lib/constants") for p in (WEB / d).rglob("*")])
        for f in files:
            if not f.is_file() or f.suffix not in (".ts", ".svelte") or f.name == "bindings.ts":
                continue
            text = read(f)
            d = first_ts_comment(text)
            if f.suffix == ".svelte" and not d:
                m = re.search(r"<script[^>]*>\s*(?:/\*\*?(.*?)\*/|//(.*?)\n)", text, re.S)
                if m:
                    d = " ".join(((m.group(1) or m.group(2)) or "").replace("*", " ").split())
            out.append(f"| `{rel(f)}` | {md_cell(d)[:260] or '—'} |\n")
    out.append("\n")
    return "".join(out)


PAGES = {
    "commands.md": gen_commands,
    "events.md": gen_events,
    "database.md": gen_database,
    "settings.md": gen_settings,
    "http-api.md": gen_http,
    "source-map.md": gen_source_map,
}


def main() -> int:
    check = "--check" in sys.argv
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, fn in PAGES.items():
        text = fn()
        target = OUT / name
        if check:
            if not target.exists() or read(target) != text:
                stale.append(name)
        else:
            target.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {rel(target)} ({len(text.splitlines())} lines)")
    for problem in sorted(set(PROBLEMS)):
        print("docs coverage: " + problem)
    if stale:
        print("Stale reference pages: " + ", ".join(stale))
        print("Run: python docs/tools/gen_reference.py")
    return 1 if (stale or PROBLEMS) else 0


if __name__ == "__main__":
    sys.exit(main())
